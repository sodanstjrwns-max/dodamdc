// Build-time only. Never uses filesystem APIs in the Worker runtime.
import { readdir, writeFile } from 'node:fs/promises'
import sharp from 'sharp'
const root = new URL('../public/static/img/', import.meta.url)
const files = (await readdir(root)).sort()
const manifest = {}
for (const file of files.filter(name => /-v\d+\.webp$/.test(name))) {
  const full = await sharp(new URL(file, root).pathname).metadata()
  const smallName = file.replace('.webp', '-sm.webp')
  if (!files.includes(smallName)) continue
  const small = await sharp(new URL(smallName, root).pathname).metadata()
  const src = '/static/img/' + file
  manifest[src] = { width: full.width, height: full.height, srcset: small.width < full.width ? `/static/img/${smallName} ${small.width}w, ${src} ${full.width}w` : `${src} ${full.width}w` }
}
await writeFile(new URL('../src/data/image-manifest.ts', import.meta.url), '// Generated by scripts/build-image-manifest.mjs; pixel dimensions from actual assets.\nexport const imageManifest: Record<string, { width: number; height: number; srcset: string }> = ' + JSON.stringify(manifest, null, 2) + '\n')
console.log(`Responsive image manifest: ${Object.keys(manifest).length} assets`)
